DROP DATABASE IF EXISTS safecampus;
CREATE DATABASE safecampus
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE safecampus;

-- ------------------------------------------------------------
-- Tabla: usuarios
-- Cubre US 01 (Registro), US 02 (Login), US 04 (Validacion),
--       US 05 (Edicion perfil)
-- ------------------------------------------------------------
CREATE TABLE usuarios (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    correo          VARCHAR(150) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    telefono        VARCHAR(20)  NULL,
    rol             ENUM('estudiante', 'monitor', 'admin') DEFAULT 'estudiante',
    is_verified     BOOLEAN DEFAULT FALSE,
    codigo_verif    VARCHAR(10)  NULL,
    estado          ENUM('activo', 'inactivo') DEFAULT 'activo',
    created_at      DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- Tabla: ubicaciones (US 06, US 07, US 08, US 09, US 10)
-- ------------------------------------------------------------
CREATE TABLE ubicaciones (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    usuario_id  INT NOT NULL,
    latitud     DECIMAL(10, 7) NOT NULL,
    longitud    DECIMAL(10, 7) NOT NULL,
    timestamp   DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
    INDEX idx_usuario_timestamp (usuario_id, timestamp)
);

-- ------------------------------------------------------------
-- Tabla: alertas (US 11, US 12, US 13, US 14, US 15)
-- ------------------------------------------------------------
CREATE TABLE alertas (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    usuario_id      INT NOT NULL,
    latitud         DECIMAL(10, 7) NOT NULL,
    longitud        DECIMAL(10, 7) NOT NULL,
    estado          ENUM('activa', 'atendida', 'falsa_alarma') DEFAULT 'activa',
    fecha_emision   DATETIME DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre    DATETIME NULL,
    monitor_id      INT NULL,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    FOREIGN KEY (monitor_id) REFERENCES usuarios(id)
);

-- ------------------------------------------------------------
-- Tabla: contactos_emergencia (US 16)
-- ------------------------------------------------------------
CREATE TABLE contactos_emergencia (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    usuario_id  INT NOT NULL,
    nombre      VARCHAR(100),
    telefono    VARCHAR(20),
    correo      VARCHAR(150),
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

